
//for loop
for(let i = 0; i <= 5; i++) {
    console.log(i);
}

//while loop
let i = 1;
while (i <= 5) {
    console.log(i);
    i++;
}


//for...of loop
let numbers = [10, 20, 30, 40];
for (let num of numbers) {
    console.log(num);
}

//for...in loop
let details={
    name:"Akshay",
    age:21
};
for(let key in details) {
    console.log(key);
    
}